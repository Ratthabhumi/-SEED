import {test,expect} from '@playwright/test';
import {startRun} from './helpers';
import {mkdirSync,writeFileSync} from 'node:fs';
type Samples={frame:number[];sim:number[];rendererCpuSubmit:number[];rendererType:number;viewport:number[];ascension:number;age:number};
test('release browser reports separate frame, sim and renderer samples',async({page,browser})=>{
  await page.setViewportSize({width:1920,height:1080});
  const diagnostic=await browser.newBrowserCDPSession();
  const system=await diagnostic.send('SystemInfo.getInfo');
  const gpu={devices:system.gpu.devices.map(d=>({vendor:d.vendorString,device:d.deviceString})),renderer:system.gpu.auxAttributes?.glRenderer??'unavailable'};
  await diagnostic.detach();
  await startRun(page,'PERF-CHILD');
  const read=()=>page.evaluate(()=>(window as unknown as {__seedE2E:{performanceSamples:()=>Samples}}).__seedE2E.performanceSamples());
  await expect.poll(async()=>(await read()).rendererCpuSubmit.length,{timeout:45000}).toBeGreaterThan(120);
  const first=await read();
  await page.evaluate(()=>(window as unknown as {__seedE2E:{readyAscend:()=>void}}).__seedE2E.readyAscend());
  await page.locator('.hud-ascend button').click();
  await page.locator('#legacy-screen .card').first().click();
  await page.locator('#origin-screen .card').first().click();
  await page.locator('#child-intro-screen button').click();
  await page.waitForTimeout(6000);
  const next=await read();
  const pct=(a:number[])=>{const s=[...a].sort((x,y)=>x-y);return [50,95,99].map(p=>s[Math.min(s.length-1,Math.floor(s.length*p/100))]);};
  const summarize=(s:Samples)=>({environment:'automated Playwright Chromium release build; GPU completion unmeasured',gpu,rendererType:s.rendererType,viewport:s.viewport,ascension:s.ascension,age:s.age,frame:pct(s.frame),simStep:pct(s.sim),rendererCpuSubmit:pct(s.rendererCpuSubmit),samples:[s.frame.length,s.sim.length,s.rendererCpuSubmit.length]});
  mkdirSync('test-results/browser',{recursive:true});
  writeFileSync('test-results/browser/renderer-evidence.json',JSON.stringify({worldOne:summarize(first),child:summarize(next)},null,2));
  expect(next.ascension).toBe(1);
  expect(next.frame.length).toBeGreaterThan(0);
  expect(next.rendererCpuSubmit.length).toBeGreaterThan(0);
  expect(next.rendererCpuSubmit.every(n=>Number.isFinite(n)&&n>=0)).toBe(true);
});